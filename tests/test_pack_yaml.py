"""Validates packs/kubernetes/pack.yaml against platform-contract §2:
every JMESPath expression compiles, every strategy/edgeType is in the
closed vocabulary, and packbuild.py's generated `types` covers every
builtin kind."""

from __future__ import annotations

import re

import jmespath
import pytest

from rwdiscovery.chain import BUILTIN_TYPES, CLUSTER, NAMESPACE, resolve_type
from rwdiscovery.enumerate import ApiResource
from rwdiscovery.packbuild import (
    build_crd_summary_expression,
    build_pack_payload,
    builtin_type_specs,
    compute_digest,
    crd_type_specs_and_summaries,
    extra_discovered_type_specs,
    load_pack_yaml,
)

# platform-contract §2's closed strategy/edgeType vocabulary.
VALID_STRATEGIES = {"reference", "owner_reference", "label_selector", "field_join", "path_template", "dns_reference"}
VALID_EDGE_TYPES = {
    "owns", "routes_to", "uses_config", "uses_secret", "mounts", "runs_as", "bound_to",
    "provisioned_by", "scaled_by", "protected_by", "governed_by", "authorized_by", "grants",
    "managed_by", "calls", "assumes_identity",
}  # fmt: skip
VALID_VOLATILITY = {"config", "state"}
VALID_POPULATOR_KINDS = {"projection", "rollup", "task", "agent"}


@pytest.fixture(scope="module")
def pack():
    return load_pack_yaml()


def test_pack_has_required_top_level_keys(pack):
    assert {"name", "version", "platform", "facetDefinitions", "dependencyRules"} <= pack.keys()
    assert "types" not in pack  # generated by packbuild.py, never hand-maintained


def test_every_facet_expression_compiles(pack):
    for facet in pack["facetDefinitions"]:
        assert facet["volatility"] in VALID_VOLATILITY, facet["key"]
        assert facet["populator"]["kind"] in VALID_POPULATOR_KINDS, facet["key"]
        expression = facet["populator"].get("expression")
        if expression:
            jmespath.compile(expression)
        for type_name, by_type_expression in (facet["populator"].get("expressionByType") or {}).items():
            jmespath.compile(by_type_expression), (facet["key"], type_name)


def test_every_dependency_rule_strategy_and_edge_type_are_in_the_closed_vocabulary(pack):
    for rule in pack["dependencyRules"]:
        assert rule["strategy"] in VALID_STRATEGIES, rule["id"]
        assert rule["edgeType"] in VALID_EDGE_TYPES, rule["id"]
        assert rule["direction"] in ("forward", "reverse"), rule["id"]


def test_every_dependency_rule_jmespath_param_compiles(pack):
    jmespath_param_names = {"values", "selector", "targetLabels", "fromValue", "toValue", "typeFrom"}
    for rule in pack["dependencyRules"]:
        for name, value in rule.get("params", {}).items():
            if name in jmespath_param_names and isinstance(value, str):
                jmespath.compile(value)


def test_dns_rule_host_keys_match_host_settings_only(pack):
    rule = next(r for r in pack["dependencyRules"] if r["id"] == "k8s.workload-calls-service-by-dns")
    host_keys = re.compile(rule["params"]["hostKeys"])
    for key in ("DATABASE_HOST", "REDIS_HOST", "host", "DB_ADDR", "SMTP_SERVER", "API_ENDPOINT", "PG_HOSTNAME"):
        assert host_keys.search(key), key
    for key in ("DATABASE_NAME", "FASTAPI_SERVICE", "OTEL_SERVICE_NAME", "GHOST_MODE", "HOSTS_FILE"):
        assert not host_keys.search(key), key


def test_dependency_rule_ids_are_unique(pack):
    ids = [rule["id"] for rule in pack["dependencyRules"]]
    assert len(ids) == len(set(ids))


def test_facet_keys_are_unique(pack):
    keys = [facet["key"] for facet in pack["facetDefinitions"]]
    assert len(keys) == len(set(keys))


def test_builtin_type_specs_cover_the_two_roots_and_every_builtin_kind():
    specs = builtin_type_specs()
    names = {s.type for s in specs}
    assert CLUSTER.type in names
    assert NAMESPACE.type in names
    assert {s.type for s in BUILTIN_TYPES.values()} <= names


_STATIC_KEYS = ("name", "version", "platform", "types", "facetDefinitions", "dependencyRules")


def test_build_pack_payload_shape_and_digest_stability():
    payload = build_pack_payload()
    assert payload["name"] == "kubernetes"
    assert {*_STATIC_KEYS, "digest", "additiveTypes", "additiveFacetDefinitions"} <= payload.keys()
    assert any(t["type"] == "deployment" for t in payload["types"])
    # Idempotent by digest (platform-contract §2): the same inputs must produce the same digest,
    # computed over the static part only -- the additive lists never feed it.
    assert compute_digest({k: payload[k] for k in _STATIC_KEYS}) == payload["digest"]
    again = build_pack_payload()
    assert again["digest"] == payload["digest"]


def _rule(pack, rule_id):
    return next(r for r in pack["dependencyRules"] if r["id"] == rule_id)


def test_generic_workload_rules_exclude_cronjob_and_include_job(pack):
    """CronJob has its own twin rule reading the deeper job-template path
    (`spec.jobTemplate.spec.template.spec...`, not `spec.template.spec...`)
    -- the dependency-rule schema has no `expressionByType` (that is a
    facet-populator-only mechanism), so one rule can't serve both shapes."""
    for rule_id in (
        "k8s.workload-uses-configmap",
        "k8s.workload-uses-secret",
        "k8s.workload-mounts-pvc",
        "k8s.workload-runs-as-serviceaccount",
    ):
        types = _rule(pack, rule_id)["from"]["types"]
        assert "cronjob" not in types, rule_id
        assert "job" in types, rule_id


def test_cronjob_uses_configmap_rule_reads_the_job_template_pod_spec(pack):
    rule = _rule(pack, "k8s.cronjob-uses-configmap")
    cronjob = {
        "spec": {
            "jobTemplate": {
                "spec": {
                    "template": {
                        "spec": {
                            "volumes": [{"name": "cfg", "configMap": {"name": "acme-cronjob-config"}}],
                            "containers": [{"name": "main", "envFrom": [{"configMapRef": {"name": "acme-main-env"}}]}],
                            "initContainers": [
                                {"name": "init", "envFrom": [{"configMapRef": {"name": "acme-init-env"}}]}
                            ],
                        }
                    }
                }
            }
        }
    }
    names = jmespath.compile(rule["params"]["values"]).search(cronjob)
    assert set(names) == {"acme-cronjob-config", "acme-main-env", "acme-init-env"}


