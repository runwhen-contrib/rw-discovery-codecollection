def test_cronjob_runs_as_serviceaccount_rule_does_not_default_incorrectly(pack):
    """The generic rule's `spec.template.spec.serviceAccountName || 'default'`
    always evaluated to nothing for a CronJob (wrong path), then silently
    defaulted every one to 'default' regardless of its real service
    account -- the CronJob-specific rule must read the real value."""
    rule = _rule(pack, "k8s.cronjob-runs-as-serviceaccount")
    with_sa = {"spec": {"jobTemplate": {"spec": {"template": {"spec": {"serviceAccountName": "acme-batch-sa"}}}}}}
    without_sa = {"spec": {"jobTemplate": {"spec": {"template": {"spec": {}}}}}}
    assert jmespath.compile(rule["params"]["values"]).search(with_sa) == "acme-batch-sa"
    assert jmespath.compile(rule["params"]["values"]).search(without_sa) == "default"


